-- Run as HACKATHON_OWNER with database HACKATHON_DB and schema APP selected:
--   USE ROLE HACKATHON_OWNER; USE DATABASE HACKATHON_DB; USE SCHEMA APP;
-- or locally/once with: python manage.py init-db
-- PK/FK/UNIQUE are informational in Snowflake; the app enforces them.

CREATE TABLE IF NOT EXISTS USERS (
    USER_ID VARCHAR(64) NOT NULL,
    AUTH_SUBJECT VARCHAR(320) NOT NULL,
    EMAIL VARCHAR(320) NOT NULL,
    PASSWORD_HASH VARCHAR(512) NOT NULL,
    DISPLAY_NAME VARCHAR(200),
    TIMEZONE VARCHAR(64) DEFAULT 'America/Indiana/Indianapolis' NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    DELETED_AT TIMESTAMP_TZ,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_AUTH_SUBJECT UNIQUE (AUTH_SUBJECT),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE IF NOT EXISTS USER_PREFERENCES (
    USER_ID VARCHAR(64) NOT NULL,
    PREFERENCE_TEXT VARCHAR(2000) DEFAULT '' NOT NULL,
    INTEREST_TAG_IDS ARRAY NOT NULL,
    EXCLUDED_TAG_IDS ARRAY NOT NULL,
    FOLLOWED_ONLY BOOLEAN DEFAULT FALSE NOT NULL,
    FREE_ONLY BOOLEAN DEFAULT FALSE NOT NULL,
    HORIZON_DAYS NUMBER(3,0) DEFAULT 30 NOT NULL,
    VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_USER_PREFERENCES PRIMARY KEY (USER_ID),
    CONSTRAINT FK_USER_PREFERENCES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID)
);

CREATE TABLE IF NOT EXISTS CLUBS (
    CLUB_ID VARCHAR(64) NOT NULL,
    SLUG VARCHAR(100) NOT NULL,
    NAME VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(4000),
    CAMPUS VARCHAR(100) DEFAULT 'purdue-west-lafayette' NOT NULL,
    WEBSITE_URL VARCHAR(1000),
    IS_VERIFIED BOOLEAN DEFAULT FALSE NOT NULL,
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_CLUBS PRIMARY KEY (CLUB_ID),
    CONSTRAINT UQ_CLUBS_SLUG UNIQUE (SLUG)
);

CREATE TABLE IF NOT EXISTS INSTAGRAM_ACCOUNTS (
    ACCOUNT_ID VARCHAR(64) NOT NULL,
    USERNAME VARCHAR(30) NOT NULL,
    INSTAGRAM_USER_ID VARCHAR(64),
    CLUB_ID VARCHAR(64),
    DISPLAY_NAME VARCHAR(200),
    BIO VARCHAR(4000),
    PROFILE_URL VARCHAR(1000) NOT NULL,
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    INGESTION_STATUS VARCHAR(16) DEFAULT 'pending' NOT NULL,
    LAST_ATTEMPT_AT TIMESTAMP_TZ,
    LAST_SUCCESS_AT TIMESTAMP_TZ,
    NEXT_RETRY_AT TIMESTAMP_TZ,
    LAST_ERROR VARCHAR(2000),
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_INSTAGRAM_ACCOUNTS PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UQ_INSTAGRAM_ACCOUNTS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_INSTAGRAM_ACCOUNTS_IG_USER_ID UNIQUE (INSTAGRAM_USER_ID),
    CONSTRAINT FK_INSTAGRAM_ACCOUNTS_CLUB FOREIGN KEY (CLUB_ID) REFERENCES CLUBS (CLUB_ID)
);

CREATE TABLE IF NOT EXISTS USER_FOLLOWS (
    USER_ID VARCHAR(64) NOT NULL,
    ACCOUNT_ID VARCHAR(64) NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_USER_FOLLOWS PRIMARY KEY (USER_ID, ACCOUNT_ID),
    CONSTRAINT FK_USER_FOLLOWS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT FK_USER_FOLLOWS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES INSTAGRAM_ACCOUNTS (ACCOUNT_ID)
);

CREATE TABLE IF NOT EXISTS TAGS (
    TAG_ID VARCHAR(64) NOT NULL,
    SLUG VARCHAR(100) NOT NULL,
    LABEL VARCHAR(200) NOT NULL,
    CATEGORY VARCHAR(16) NOT NULL,
    DESCRIPTION VARCHAR(1000),
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_TAGS PRIMARY KEY (TAG_ID),
    CONSTRAINT UQ_TAGS_SLUG UNIQUE (SLUG)
);

CREATE TABLE IF NOT EXISTS CLUB_TAGS (
    CLUB_ID VARCHAR(64) NOT NULL,
    TAG_ID VARCHAR(64) NOT NULL,
    SOURCE VARCHAR(16) NOT NULL,
    CONFIDENCE FLOAT,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_CLUB_TAGS PRIMARY KEY (CLUB_ID, TAG_ID),
    CONSTRAINT FK_CLUB_TAGS_CLUB FOREIGN KEY (CLUB_ID) REFERENCES CLUBS (CLUB_ID),
    CONSTRAINT FK_CLUB_TAGS_TAG FOREIGN KEY (TAG_ID) REFERENCES TAGS (TAG_ID)
);

CREATE TABLE IF NOT EXISTS POSTS (
    POST_ID VARCHAR(64) NOT NULL,
    SHORTCODE VARCHAR(64) NOT NULL,
    INSTAGRAM_MEDIA_ID VARCHAR(64),
    ACCOUNT_ID VARCHAR(64) NOT NULL,
    PERMALINK VARCHAR(1000) NOT NULL,
    POSTED_AT TIMESTAMP_TZ NOT NULL,
    CAPTION VARCHAR(16777216),
    MEDIA_TYPE VARCHAR(16) NOT NULL,
    MEDIA_URLS ARRAY NOT NULL,
    OCR_TEXT VARCHAR(16777216),
    RAW_PAYLOAD VARIANT,
    CONTENT_HASH VARCHAR(64) NOT NULL,
    EXTRACTION_STATUS VARCHAR(16) DEFAULT 'pending' NOT NULL,
    EXTRACTION_VERSION VARCHAR(200),
    EXTRACTED_PAYLOAD VARIANT,
    ATTEMPT_COUNT NUMBER(5,0) DEFAULT 0 NOT NULL,
    LEASE_EXPIRES_AT TIMESTAMP_TZ,
    LAST_ERROR VARCHAR(2000),
    INGESTED_AT TIMESTAMP_TZ NOT NULL,
    SOURCE_SEEN_AT TIMESTAMP_TZ NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    DELETED_AT TIMESTAMP_TZ,
    CONSTRAINT PK_POSTS PRIMARY KEY (POST_ID),
    CONSTRAINT UQ_POSTS_SHORTCODE UNIQUE (SHORTCODE),
    CONSTRAINT UQ_POSTS_MEDIA_ID UNIQUE (INSTAGRAM_MEDIA_ID),
    CONSTRAINT FK_POSTS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES INSTAGRAM_ACCOUNTS (ACCOUNT_ID)
);

CREATE TABLE IF NOT EXISTS EVENTS (
    EVENT_ID VARCHAR(64) NOT NULL,
    DEDUPE_KEY VARCHAR(64) NOT NULL,
    CLUB_ID VARCHAR(64) NOT NULL,
    TITLE VARCHAR(500) NOT NULL,
    DESCRIPTION VARCHAR(4000),
    START_AT TIMESTAMP_TZ,
    END_AT TIMESTAMP_TZ,
    LOCAL_START_DATE DATE,
    EVENT_TIMEZONE VARCHAR(64) DEFAULT 'America/Indiana/Indianapolis' NOT NULL,
    DATE_PRECISION VARCHAR(16) NOT NULL,
    LOCATION_NAME VARCHAR(500),
    LOCATION_ADDRESS VARCHAR(1000),
    LOCATION_URL VARCHAR(1000),
    REGISTRATION_URL VARCHAR(1000),
    PRICE_AMOUNT NUMBER(10,2),
    PRICE_CURRENCY VARCHAR(3) DEFAULT 'USD' NOT NULL,
    IS_FREE BOOLEAN,
    STATUS VARCHAR(16) DEFAULT 'draft' NOT NULL,
    CONFIDENCE FLOAT,
    EXTRACTION_VERSION VARCHAR(200),
    SEARCH_TEXT VARCHAR(16777216) NOT NULL,
    REVISION NUMBER(10,0) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_EVENTS PRIMARY KEY (EVENT_ID),
    CONSTRAINT UQ_EVENTS_DEDUPE_KEY UNIQUE (DEDUPE_KEY),
    CONSTRAINT FK_EVENTS_CLUB FOREIGN KEY (CLUB_ID) REFERENCES CLUBS (CLUB_ID)
);

CREATE TABLE IF NOT EXISTS EVENT_TAGS (
    EVENT_ID VARCHAR(64) NOT NULL,
    TAG_ID VARCHAR(64) NOT NULL,
    SOURCE VARCHAR(16) NOT NULL,
    CONFIDENCE FLOAT,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_EVENT_TAGS PRIMARY KEY (EVENT_ID, TAG_ID),
    CONSTRAINT FK_EVENT_TAGS_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS (EVENT_ID),
    CONSTRAINT FK_EVENT_TAGS_TAG FOREIGN KEY (TAG_ID) REFERENCES TAGS (TAG_ID)
);

CREATE TABLE IF NOT EXISTS EVENT_SOURCES (
    EVENT_ID VARCHAR(64) NOT NULL,
    POST_ID VARCHAR(64) NOT NULL,
    SOURCE_EVENT_KEY VARCHAR(64) NOT NULL,
    IS_PRIMARY BOOLEAN DEFAULT FALSE NOT NULL,
    EVIDENCE VARIANT,
    SOURCE_CONTENT_HASH VARCHAR(64) NOT NULL,
    EXTRACTION_VERSION VARCHAR(200) NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_EVENT_SOURCES PRIMARY KEY (EVENT_ID, POST_ID),
    CONSTRAINT UQ_EVENT_SOURCES_POST_KEY UNIQUE (POST_ID, SOURCE_EVENT_KEY),
    CONSTRAINT FK_EVENT_SOURCES_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS (EVENT_ID),
    CONSTRAINT FK_EVENT_SOURCES_POST FOREIGN KEY (POST_ID) REFERENCES POSTS (POST_ID)
);
