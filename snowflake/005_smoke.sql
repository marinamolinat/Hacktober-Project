-- Read-only account inspection. Run explicitly; this is not an automated test.
USE ROLE HACKATHON_OWNER;
USE WAREHOUSE HACKATHON_APP_WH;
ALTER SESSION SET TIMEZONE = 'UTC';
SELECT CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), CURRENT_REGION(),
       CURRENT_ROLE(), CURRENT_WAREHOUSE();
SELECT COUNT(*) AS BASE_TABLE_COUNT
FROM HACKATHON_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'APP' AND TABLE_TYPE = 'BASE TABLE';
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM HACKATHON_DB.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'APP'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
SHOW CORTEX SEARCH SERVICES IN SCHEMA HACKATHON_DB.APP;
SHOW AGENTS IN SCHEMA HACKATHON_DB.APP;
SHOW PARAMETERS LIKE 'CORTEX_ENABLED_CROSS_REGION' IN ACCOUNT;

USE ROLE HACKATHON_API;
USE SECONDARY ROLES NONE;
SELECT COUNT(*) AS EVENT_COUNT FROM HACKATHON_DB.APP.EVENTS;
SELECT COUNT(*) AS TAG_COUNT FROM HACKATHON_DB.APP.TAGS;
SHOW GRANTS TO ROLE HACKATHON_API;
