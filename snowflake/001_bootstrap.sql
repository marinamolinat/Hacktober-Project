-- Run once as an account administrator. No passwords or private keys belong here.
-- These files preserve existing objects; they do not reconcile older definitions.
USE ROLE ACCOUNTADMIN;
ALTER SESSION SET TIMEZONE = 'UTC';
ALTER SESSION SET STATEMENT_TIMEOUT_IN_SECONDS = 120;

CREATE ROLE IF NOT EXISTS HACKATHON_OWNER;
CREATE ROLE IF NOT EXISTS HACKATHON_API;
CREATE ROLE IF NOT EXISTS HACKATHON_INGEST;
GRANT ROLE HACKATHON_API TO ROLE HACKATHON_OWNER;
GRANT ROLE HACKATHON_INGEST TO ROLE HACKATHON_OWNER;
GRANT ROLE HACKATHON_OWNER TO ROLE SYSADMIN;
SET setup_operator = CURRENT_USER();
GRANT ROLE HACKATHON_OWNER TO USER IDENTIFIER($setup_operator);

CREATE WAREHOUSE IF NOT EXISTS HACKATHON_APP_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS HACKATHON_SEARCH_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE HACKATHON_APP_WH TO ROLE HACKATHON_OWNER;
GRANT USAGE, OPERATE ON WAREHOUSE HACKATHON_SEARCH_WH TO ROLE HACKATHON_OWNER;
GRANT USAGE ON WAREHOUSE HACKATHON_APP_WH TO ROLE HACKATHON_API;
GRANT USAGE ON WAREHOUSE HACKATHON_APP_WH TO ROLE HACKATHON_INGEST;

CREATE DATABASE IF NOT EXISTS HACKATHON_DB DATA_RETENTION_TIME_IN_DAYS = 1;
GRANT USAGE, CREATE SCHEMA ON DATABASE HACKATHON_DB TO ROLE HACKATHON_OWNER;
GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE HACKATHON_API;
GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE HACKATHON_INGEST;

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE HACKATHON_OWNER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE HACKATHON_API;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE HACKATHON_INGEST;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE HACKATHON_OWNER;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE HACKATHON_API;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE HACKATHON_INGEST;

USE ROLE HACKATHON_OWNER;
CREATE SCHEMA IF NOT EXISTS HACKATHON_DB.APP DATA_RETENTION_TIME_IN_DAYS = 1;
GRANT USAGE ON SCHEMA HACKATHON_DB.APP TO ROLE HACKATHON_API;
GRANT USAGE ON SCHEMA HACKATHON_DB.APP TO ROLE HACKATHON_INGEST;

